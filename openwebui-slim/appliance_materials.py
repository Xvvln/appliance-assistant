def reference_section(p: dict) -> str:
    return (f'\n\n## {p["model"]}· 资料来源与边界\n\n'
            f'参考型号：{p["reference_model"]}。'
            f'[品牌产品参数]({p["reference_url"]})；'
            f'[参考型号使用说明]({p["reference_manual_url"]})。核对日期：2026-10-23。\n\n'
            '容量、尺寸和主要功能参考上述资料；本型号名称、外观、面板操作、安装空间约束与经营价格为本产品线设定，'
            '不是该品牌授权商品或官方说明书。未复用能效认证、除菌率、实测噪声、保修承诺与真实品牌故障代码。'
            '参考说明书只用于追溯；本说明中的操作不可直接套用于真实品牌机器。\n')


